// Builds docs/ASVS_CHECKLIST.md (P7.2) from two files:
//  - docs/asvs/asvs-5.0.0-en.flat.json: OWASP ASVS 5.0.0, as published in the
//    OWASP/ASVS repository (5.0/docs_en), CC BY-SA 4.0. The requirement text in the
//    checklist is copied from it, never written from memory.
//  - docs/asvs/assessment.json: Zeno's status and evidence per requirement.
// Every Level 1 and Level 2 requirement gets a row; one with no assessment yet says
// so. `--check` exits non-zero if the checklist on disk is not what the two files
// produce, if an assessment cites a file that does not exist, or if a status is
// not one of the four allowed (no "believed"; P7's gate).
//   node scripts/asvs-checklist.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "docs/ASVS_CHECKLIST.md");
export const STATUSES = { met: "Met", partial: "Partial", open: "Open", na: "N/A" };

export function load() {
  const asvs = JSON.parse(readFileSync(resolve(ROOT, "docs/asvs/asvs-5.0.0-en.flat.json"), "utf8")).requirements;
  const assessment = JSON.parse(readFileSync(resolve(ROOT, "docs/asvs/assessment.json"), "utf8"));
  return { asvs, assessment };
}

/** Problems with the assessment: unknown ids, bad statuses, missing owners or files. */
export function problems(asvs, assessment) {
  const ids = new Set(asvs.map((r) => r.req_id));
  const out = [];
  for (const [id, a] of Object.entries(assessment)) {
    if (!ids.has(id)) out.push(`${id}: not an ASVS 5.0 requirement`);
    if (!(a.status in STATUSES)) out.push(`${id}: status "${a.status}" is not one of ${Object.keys(STATUSES).join(", ")}`);
    if (!a.note || !a.note.trim()) out.push(`${id}: no note`);
    if ((a.status === "open" || a.status === "partial") && !a.owner) out.push(`${id}: ${a.status} without an owner`);
    if (a.status === "met" && (!a.evidence || a.evidence.length === 0)) out.push(`${id}: met without evidence`);
    for (const file of a.evidence ?? []) if (!existsSync(resolve(ROOT, file))) out.push(`${id}: evidence ${file} does not exist`);
  }
  return out;
}

// OWASP's text is Markdown already (its "\*" and "\_" are meant), so backslashes
// are kept. A "|" would end the table cell: written as an entity, which no
// backslash before it can undo (CodeQL js/incomplete-sanitization).
const cell = (text) => String(text).replace(/\|/g, "&#124;").replace(/\s+/g, " ").trim();

export function render(asvs, assessment) {
  const scoped = asvs.filter((r) => r.L === "1" || r.L === "2");
  const counts = { met: 0, partial: 0, open: 0, na: 0, todo: 0 };
  for (const r of scoped) counts[assessment[r.req_id]?.status ?? "todo"] += 1;
  const lines = [
    "# ASVS 5.0 Level 2 checklist (P7.2)",
    "",
    "Zeno's API and website against **OWASP ASVS 5.0.0**, Levels 1 and 2. The requirement",
    "text is copied from OWASP's published file (`docs/asvs/asvs-5.0.0-en.flat.json`, from the",
    "OWASP/ASVS repository, CC BY-SA 4.0), not written from memory. The phone app is assessed",
    "against MASVS (`docs/MASVS_CHECKLIST.md`). This file is generated by",
    "`scripts/asvs-checklist.mjs` from `docs/asvs/assessment.json`; edit that, not this.",
    "",
    "**Status:** **Met**: holds, with the evidence named. **Partial**: part holds; the gap and",
    "its owner are named. **Open**: not done; owner named. **N/A**: nothing in Zeno it applies",
    "to, with the reason. A row still to be assessed says so. Nothing is marked as believed.",
    "",
    `**So far:** ${scoped.length} requirements at Level 1 or 2: ${counts.met} met, ${counts.partial} partial, ${counts.open} open, ${counts.na} not applicable, ${counts.todo} not yet assessed.`,
    ""
  ];
  let chapter = "";
  let section = "";
  for (const r of scoped) {
    if (r.chapter_id !== chapter) {
      chapter = r.chapter_id;
      lines.push(`## ${r.chapter_id} ${r.chapter_name}`, "");
    }
    if (r.section_id !== section) {
      section = r.section_id;
      lines.push(`### ${r.section_id} ${r.section_name}`, "", "| Requirement | L | Status | Evidence and notes |", "|---|---|---|---|");
    }
    const a = assessment[r.req_id];
    const status = a ? `**${STATUSES[a.status]}**${a.owner ? ` (owner: ${a.owner})` : ""}` : "*not yet assessed*";
    const evidence = a ? [a.note, ...(a.evidence ?? []).map((f) => `\`${f}\``)].join(" ") : "";
    lines.push(`| **${r.req_id}** ${cell(r.req_description)} | ${r.L} | ${status} | ${cell(evidence)} |`);
    const next = scoped[scoped.indexOf(r) + 1];
    if (!next || next.section_id !== section) lines.push("");
  }
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { asvs, assessment } = load();
  const found = problems(asvs, assessment);
  const text = render(asvs, assessment);
  if (process.argv.includes("--check")) {
    const stale = !existsSync(OUT) || readFileSync(OUT, "utf8") !== text;
    if (stale) found.push("docs/ASVS_CHECKLIST.md is not what the assessment produces: run node scripts/asvs-checklist.mjs");
    for (const p of found) console.error(p);
    process.exit(found.length ? 1 : 0);
  }
  if (found.length) {
    for (const p of found) console.error(p);
    process.exit(1);
  }
  writeFileSync(OUT, text);
  console.log("wrote docs/ASVS_CHECKLIST.md");
}
